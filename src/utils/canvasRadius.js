/* ============================================================
   圆角半径补偿
   ------------------------------------------------------------
   节点的圆角写在「世界坐标」里，而世界层整体被 CSS scale() 缩放过：
   8px 圆角在 100% 时是 8px，缩到 20% 就只剩 1.6 个屏幕像素 ——
   浏览器做像素量化后，四角会直接变成直角，「圆角」这件事就消失了。

   这里给圆角加一条屏幕空间的兜底线：无论怎么缩小，圆角在屏幕上
   至少保留 MIN_SCREEN_RADIUS 个像素；放大时不干预（继续用设计值，
   不会越放越圆）。同时用「短边的一半」封顶，避免小卡片被圆成胶囊。
   ============================================================ */

/** 屏幕上的最小圆角（px）：缩略到 20% 时仍能一眼看出这是圆角卡片 */
const MIN_SCREEN_RADIUS = 3.5

/**
 * 计算元素在指定缩放下的圆角半径（世界坐标 px）
 * @param {number} base   设计值（世界坐标，如节点 8 / 表格 5）
 * @param {number} w      元素世界宽度
 * @param {number} h      元素世界高度
 * @param {number} scale  画布缩放比例
 */
export function cornerRadius(base, w, h, scale) {
  const minWorld = MIN_SCREEN_RADIUS / Math.max(scale, 0.01)
  // 短边一半封顶：极小的元素最多圆成胶囊，不会出现畸形
  return Math.min(Math.min(w, h) / 2, Math.max(base, minWorld))
}
